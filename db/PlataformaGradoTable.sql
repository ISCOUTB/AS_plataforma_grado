  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_DOBLE_TITULACION" ("ID_USUARIO", "NOMBRE_COMPLETO", "DISTINCION") AS 
  SELECT 
    u.id_usuario,
    u.nombre_completo,
    'DOBLE_TITULACION' AS distincion
