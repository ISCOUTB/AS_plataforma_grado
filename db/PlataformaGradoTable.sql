create or replace FUNCTION calcular_ppa (
    p_id_usuario IN NUMBER
) RETURN NUMBER IS
    v_suma_ponderada NUMBER := 0;
    v_suma_creditos  NUMBER := 0;
    v_ppa            NUMBER := 0;
BEGIN
    -- Sumar notas * créditos y créditos totales
    SELECT 
        NVL(SUM(uc.nota * c.creditos), 0),
        NVL(SUM(c.creditos), 0)
    INTO 
        v_suma_ponderada,
        v_suma_creditos
    FROM USUARIO_CURSO uc
    JOIN CURSO c ON uc.id_curso = c.id_curso
    WHERE uc.id_usuario = p_id_usuario
      AND uc.estado = 'APROBADO';

    -- Calcular PPA
    IF v_suma_creditos > 0 THEN
        v_ppa := v_suma_ponderada / v_suma_creditos;
    ELSE
        v_ppa := 0;
    END IF;
    -- Guardar resultados en USUARIO
    UPDATE USUARIO
    SET PPA = ROUND(v_ppa, 2)
    WHERE ID_USUARIO = p_id_usuario;

    COMMIT;

    RETURN v_ppa;
END;
