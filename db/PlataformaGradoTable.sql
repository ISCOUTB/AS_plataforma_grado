create or replace FUNCtION custom_login(
    p_username VARCHAR2,
    p_password VARCHAR2
)RETURN BOOLEAN

IS 
    l_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO l_count
    FROM USUARIO
    WHERE UPPER(CORREO_INSTITUCIONAL) = UPPER(p_username)
    AND CONTRASENA = p_password;

    IF l_count > 0 THEN
        RETURN TRUE;
    ELSE
        RETURN FALSE;
    END IF;
END;
