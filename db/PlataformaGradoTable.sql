create or replace FUNCTION obtener_periodo_academico (
    p_fecha IN DATE DEFAULT SYSDATE
) RETURN VARCHAR2
IS
    l_anio NUMBER;
    l_semestre VARCHAR2(10);
    l_mes NUMBER;
BEGIN
    l_anio := EXTRACT(YEAR FROM p_fecha);
    l_mes := EXTRACT(MONTH FROM p_fecha);
    
    -- Enero-Junio: Semestre I
    -- Agosto-Diciembre: Semestre II
    IF l_mes BETWEEN 1 AND 6 THEN
        l_semestre := 'I';
    ELSE
        l_semestre := 'II';
    END IF;
    
    RETURN l_anio || '-' || l_semestre;
END obtener_periodo_academico;
