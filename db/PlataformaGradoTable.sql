  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_ESTUDIANTES_APROBADOS_DISTINCIONES" ("ID_USUARIO", "NOMBRE_COMPLETO", "CORREO_INSTITUCIONAL", "ID_PROGRAMA", "PPA", "ES_DOBLE_TITULACION", "TRABAJO_LAUREADO", "DISTINCION_PPA", "ESTUDIANTE_HONOR", "ESTUDIANTE_MERITORIO") AS 
  WITH base AS (
    SELECT 
        u.id_usuario,
        u.nombre_completo,
        u.correo_institucional,
        u.id_programa,
        u.es_doble_titulacion,
        u.ppa,
        u.prueba_academica,
        p.escuela,

        (
            SELECT COUNT(*) 
            FROM usuario_curso uc 
            WHERE uc.id_usuario = u.id_usuario
              AND (uc.estado = 'CANCELADO' OR uc.nota < 3)
        ) AS cursos_malos,

        (
            SELECT COUNT(*) 
            FROM sancion_usuario su
            WHERE su.id_usuario = u.id_usuario
              AND su.activa = 'S'
        ) AS sanciones_activas,

        (
            SELECT CASE 
                     WHEN MAX(CASE WHEN uc.laureado = 'S' THEN 1 ELSE 0 END) = 1 
                     THEN 'SI' 
                     ELSE 'NO'
                   END
            FROM usuario_curso uc
            WHERE uc.id_usuario = u.id_usuario
        ) AS trabajo_laureado
    FROM usuario u
    JOIN programa_academico p ON p.id_programa = u.id_programa
    JOIN solicitud_grado sg ON sg.id_usuario = u.id_usuario
    WHERE UPPER(sg.estado) = 'APROBADA'
),
ranking AS (
    SELECT 
        b.*,
        ROW_NUMBER() OVER (PARTITION BY b.escuela ORDER BY b.ppa DESC) AS rn
    FROM base b
)
SELECT
    r.id_usuario,
    r.nombre_completo,
    r.correo_institucional,
    r.id_programa,
    r.ppa,
    r.es_doble_titulacion,
    r.trabajo_laureado,

    CASE 
        WHEN r.ppa >= 4.8 
             AND r.cursos_malos = 0
             AND r.sanciones_activas = 0
             AND r.prueba_academica = 'N'
        THEN 'Summa Cum Laude'

        WHEN r.ppa >= 4.6 
             AND r.cursos_malos = 0
             AND r.sanciones_activas = 0
             AND r.prueba_academica = 'N'
        THEN 'Cum Laude'

        ELSE 'Sin Distinción'
    END AS distincion_ppa,

    CASE WHEN r.rn = 1 THEN 'SI' ELSE 'NO' END AS estudiante_honor,
    CASE WHEN r.rn = 2 THEN 'SI' ELSE 'NO' END AS estudiante_meritorio

FROM ranking r
ORDER BY r.ppa DESC;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_GRADUABLE" ("ID_USUARIO", "NOMBRE_COMPLETO", "ID_PROGRAMA", "CURSOS_APROBADOS", "TOTAL_PENSUM_CURSOS", "GRADUABLE") AS 
  SELECT u.id_usuario,
       u.nombre_completo,
       u.id_programa,
       NVL(a.CURSOS_APROBADOS,0) AS CURSOS_APROBADOS,
       NVL(p.TOTAL_CURSOS,0)     AS TOTAL_PENSUM_CURSOS,
       CASE 
         WHEN NVL(a.CURSOS_APROBADOS,0) >= NVL(p.TOTAL_CURSOS,0)
              AND NOT EXISTS (
                 SELECT 1 FROM sancion_usuario s
                 WHERE s.id_usuario = u.id_usuario AND s.activa = 'S'
              )
         THEN 'S' ELSE 'N' END AS GRADUABLE
FROM usuario u
LEFT JOIN VW_USUARIO_CURSOS_APROBADOS a ON a.id_usuario = u.id_usuario AND a.id_pensum = u.id_pensum
LEFT JOIN VW_PENSUM_TOTAL_CURSOS p ON p.id_pensum = u.id_pensum;

