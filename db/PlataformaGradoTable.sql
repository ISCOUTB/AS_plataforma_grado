create or replace PROCEDURE redirigir_post_login AS
  v_rol VARCHAR2(100);
  v_url VARCHAR2(4000);
BEGIN
  APEX_DEBUG.ENABLE(p_level => 4); -- Habilita logs

  BEGIN
    SELECT rol
    INTO v_rol
    FROM usuario
    WHERE UPPER(correo_institucional) = UPPER(apex_application.g_user);

    APEX_DEBUG.MESSAGE('Rol encontrado: ' || v_rol);
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      v_rol := NULL;
      APEX_DEBUG.MESSAGE('No se encontró el usuario: ' || apex_application.g_user);
  END;

  IF v_rol IS NOT NULL AND TRIM(UPPER(v_rol)) = 'ADMIN' THEN
    v_url := apex_page.get_url(p_page => 6);
    APEX_DEBUG.MESSAGE('Redirigiendo a página ADMIN (6)');
  ELSE
    v_url := apex_page.get_url(p_page => 1);
    APEX_DEBUG.MESSAGE('Redirigiendo a página normal (1)');
  END IF;

  APEX_DEBUG.MESSAGE('URL generada: ' || v_url);

  apex_util.redirect_url(v_url);
  APEX_DEBUG.MESSAGE('Redirección ejecutada');
EXCEPTION
  WHEN OTHERS THEN
    APEX_DEBUG.MESSAGE('Error en redirigir_post_login: ' || SQLERRM);
END;
/























































